// Keeps the launch workplan and the launch checklist in the admin in step (workplan A17).
//
// The checklist in D1 is the source of truth for each item's status, owner, what it waits on and
// its parts, because Alex and Amber change those in the admin and Amber never edits this repo.
// The workplan stays the record of what each item involves and the evidence that closed it.
//
//   node app/ops/checklist.mjs export [--local]        write app/docs/launch-checklist-status.md from D1
//   node app/ops/checklist.mjs drift  [--local]        list where the workplan and the checklist disagree
//   node app/ops/checklist.mjs done <workplan id> --note "evidence" [--local]
//
// Sessions run export and read the status file before picking up launch work, and run done
// when they close a workplan item, which ticks it as Claude with the evidence as a comment.
// Without --local each command reads the hosted database through admin/wrangler.hosted.jsonc.
// WARNING: done writes to that database. It changes one item and adds its audit row and comment.

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WRANGLER = process.env.WRANGLER_JS || path.resolve(APP, '../../teapup-website-repo/admin/node_modules/wrangler/bin/wrangler.js');
const WORKPLAN = path.join(APP, 'docs/launch-workplan.md');
const STATUS_FILE = path.join(APP, 'docs/launch-checklist-status.md');

/** The items in the workplan header, as { id, status, closed }. */
export function workplanItems(text) {
  const head = text.split(/^---$/m)[1] || '';
  return [...head.matchAll(/^\s*- \{id: ([A-Z]\d+), status: ("[^"]*"|[\w-]+)/gm)].map((m) => {
    const status = m[2].replace(/^"|"$/g, '');
    return { id: m[1], status, closed: status === 'closed', moved: /^moved to /i.test(status) };
  });
}

// Workplan items that are a part of another item on the checklist rather than an item of their
// own. The seller statement wording is Amber's part of the seller statement item.
export const MERGED = { D5: 'A6' };

/** Where the two disagree. rows are checklist items with ref, status and archived_at. */
export function drift(items, rows) {
  const byRef = new Map(rows.filter((r) => r.ref).map((r) => [r.ref, r]));
  const out = [];
  for (const it of items) {
    if (it.moved || MERGED[it.id]) continue;
    const r = byRef.get(it.id);
    if (!r) { out.push(`${it.id} is in the workplan and not on the checklist`); continue; }
    if (r.archived_at) out.push(`${it.id} is archived on the checklist and ${it.closed ? 'closed' : 'open'} in the workplan`);
    else if (it.closed && r.status !== 'done') out.push(`${it.id} is closed in the workplan and ${r.status} on the checklist`);
    else if (!it.closed && r.status === 'done') out.push(`${it.id} is done on the checklist and still open in the workplan`);
  }
  const ids = new Set(items.map((i) => i.id));
  for (const r of rows) if (r.ref && !ids.has(r.ref)) out.push(`${r.ref} is on the checklist and not in the workplan`);
  return out;
}

function d1(command, local) {
  const args = [WRANGLER, 'd1', 'execute', 'puppyconnection', '--json', '--command', command];
  if (local) args.push('--local', '--persist-to', path.join(APP, '.state'), '--config', path.join(APP, 'admin/wrangler.jsonc'));
  else args.push('--remote', '--config', path.join(APP, 'admin/wrangler.hosted.jsonc'));
  const out = execFileSync(process.execPath, args, { cwd: APP, stdio: ['ignore', 'pipe', 'pipe'] }).toString();
  return JSON.parse(out.slice(out.indexOf('[')));
}
const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const yq = (v) => (v == null ? 'null' : JSON.stringify(String(v)));

function readRows(local) {
  const items = d1('SELECT id, ref, section, position, title, owner, status, waiting_on, waiting_owner, done_at, done_by, archived_at FROM checklist_items ORDER BY section, position', local)[0].results;
  const parts = d1('SELECT item_id, title, owner, done_at, done_by FROM checklist_parts WHERE archived_at IS NULL ORDER BY item_id, position', local)[0].results;
  for (const it of items) it.parts = parts.filter((p) => p.item_id === it.id);
  return items;
}

function exportStatus(local) {
  const rows = readRows(local);
  const live = rows.filter((r) => !r.archived_at);
  const lines = ['---', 'title: "Launch checklist status, exported from the admin"',
    `exported: ${new Date().toISOString().slice(0, 19)}Z`,
    `source: "${local ? 'local' : 'hosted'} D1, checklist_items and checklist_parts. The admin is the source of truth for status, owner and parts. Do not edit this file, run node app/ops/checklist.mjs export again"`,
    'items:'];
  for (const r of live) {
    const parts = r.parts.length ? `, parts: "${r.parts.filter((p) => p.done_at).length} of ${r.parts.length} done", open_parts: [${r.parts.filter((p) => !p.done_at).map((p) => yq(`${p.owner}: ${p.title}`)).join(', ')}]` : '';
    lines.push(`  - {ref: ${r.ref || 'null'}, section: ${r.section}, title: ${yq(r.title)}, owner: ${r.owner}, status: ${r.status}${
      r.status === 'waiting' ? `, waiting_on: ${yq(r.waiting_on)}` : ''}${r.done_at ? `, done: ${r.done_at.slice(0, 10)}, done_by: ${yq(r.done_by)}` : ''}${parts}}`);
  }
  const archived = rows.filter((r) => r.archived_at);
  if (archived.length) {
    lines.push('archived:');
    for (const r of archived) lines.push(`  - {ref: ${r.ref || 'null'}, title: ${yq(r.title)}, archived: ${r.archived_at.slice(0, 10)}}`);
  }
  const problems = drift(workplanItems(fs.readFileSync(WORKPLAN, 'utf8')), rows);
  lines.push(`drift: [${problems.map(yq).join(', ')}]`, '---', '',
    'The launch checklist lives in the admin at #/checklist, where Alex and Amber tick, assign and',
    'comment. This file is a copy of its state for sessions to read. The workplan',
    '(launch-workplan.md) keeps what each item involves and the evidence that closed it.', '');
  fs.writeFileSync(STATUS_FILE, lines.join('\n'));
  console.log(`wrote ${path.relative(process.cwd(), STATUS_FILE)}: ${live.length} items, ${archived.length} archived, ${problems.length} drift`);
  for (const p of problems) console.log(`  drift: ${p}`);
}

function markDone(ref, note, local) {
  if (!/^[A-Z]\d+$/.test(ref || '')) throw new Error('Give the workplan id, for example A6.');
  if (!note) throw new Error('Give the evidence with --note.');
  const t = `${new Date().toISOString().slice(0, 19)}Z`;
  const id = `(SELECT id FROM checklist_items WHERE ref = ${q(ref)})`;
  const cid = `cmt-${ref}-${Date.now()}`;
  const before = d1(`SELECT status, archived_at FROM checklist_items WHERE ref = ${q(ref)}`, local)[0].results[0];
  if (!before) throw new Error(`${ref} is not on the checklist.`);
  if (before.status === 'done') { console.log(`${ref} is already done on the checklist.`); return; }
  d1([
    `UPDATE checklist_items SET status = 'done', done_at = ${q(t)}, done_by = 'Claude', waiting_on = NULL, waiting_owner = NULL, updated_at = ${q(t)}, version = version + 1 WHERE ref = ${q(ref)} AND status != 'done'`,
    `INSERT INTO checklist_comments (id, item_id, author, author_email, body, created_at) VALUES (${q(cid)}, ${id}, 'Claude', 'claude', ${q(note.slice(0, 4000))}, ${q(t)})`,
    `INSERT INTO audit_log (at, actor_type, actor, action, entity, entity_id, before_json, after_json) VALUES (${q(t)}, 'system', 'claude', 'checklist.tick', 'checklist_item', ${id}, ${
      q(JSON.stringify({ status: before.status }))}, ${q(JSON.stringify({ status: 'done', as: 'Claude' }))})`,
  ].join('; '), local);
  console.log(`${ref} ticked done as Claude, with the evidence as a comment.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const [cmd, ...rest] = process.argv.slice(2);
  const local = rest.includes('--local');
  const noteAt = rest.indexOf('--note');
  try {
    if (cmd === 'export') exportStatus(local);
    else if (cmd === 'drift') {
      const problems = drift(workplanItems(fs.readFileSync(WORKPLAN, 'utf8')), readRows(local));
      console.log(problems.length ? problems.join('\n') : 'The workplan and the checklist agree.');
      process.exitCode = problems.length ? 1 : 0;
    } else if (cmd === 'done') markDone(rest[0], noteAt >= 0 ? rest[noteAt + 1] : null, local);
    else { console.log('Use export, drift or done. See the top of this file.'); process.exitCode = 2; }
  } catch (e) { console.error(e.message); process.exitCode = 1; }
}
