// Writes migrations/0034_launch_checklist.sql from ops/checklist-seed.mjs (workplan A17).
//
//   node app/dev/make-checklist-migration.mjs
//
// The tables are the same text as in schema.sql, so a new database and a migrated one match.
// The seed rows have fixed ids, so running the file twice adds nothing the second time.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SEED, SIGNERS } from '../ops/checklist-seed.mjs';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(APP, 'migrations/0034_launch_checklist.sql');
const AT = '2026-10-19T12:00:00Z';
const BY = 'launch plan';

const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const dayAt = (d) => (d ? `${d}T12:00:00Z` : null);

const schema = fs.readFileSync(path.join(APP, 'schema.sql'), 'utf8');
const start = schema.indexOf('-- Launch checklist (workplan A17)');
const end = schema.indexOf('-- end of launch checklist');
if (start < 0 || end < 0) throw new Error('schema.sql has no launch checklist block');
const tables = schema.slice(start, end).trim();

const lines = [
  '-- The launch checklist in the admin (workplan A17, Alex 2026-10-19). Generated by',
  '-- dev/make-checklist-migration.mjs from ops/checklist-seed.mjs. Re-running adds nothing.',
  '-- Back up D1 first and confirm the export printed "Downloaded" (README, deliberate choices).',
  '',
  tables,
  '',
];
const pos = {};
SEED.forEach((it, i) => {
  const id = `cl-${String(i + 1).padStart(3, '0')}`;
  pos[it.section] = (pos[it.section] || 0) + 1;
  const done = it.status === 'done';
  lines.push(`INSERT OR IGNORE INTO checklist_items (id, ref, section, position, title, description, owner, status, waiting_on, waiting_owner, done_at, done_by, created_at, created_by, updated_at, version) VALUES (${
    [id, it.ref || null, it.section].map(q).join(', ')}, ${pos[it.section]}, ${[it.title, it.desc, it.owner, it.status, it.waiting || null, it.waitingOwner || null,
    done ? dayAt(it.done) : null, done ? BY : null, AT, BY, AT].map(q).join(', ')}, 1);`);
  (it.parts || []).forEach((p, j) => {
    lines.push(`INSERT OR IGNORE INTO checklist_parts (id, item_id, position, title, owner, done_at, done_by, created_at, created_by) VALUES (${
      [`${id}-${j + 1}`, id].map(q).join(', ')}, ${j + 1}, ${[p.title, p.owner, dayAt(p.done), p.done ? BY : null, AT, BY].map(q).join(', ')});`);
  });
});
for (const [email, names] of SIGNERS) lines.push(`INSERT OR IGNORE INTO checklist_signers (email, names) VALUES (${q(email)}, ${q(names)});`);
lines.push(`INSERT INTO audit_log (at, actor_type, actor, action, entity, entity_id, before_json, after_json) SELECT ${q(AT)}, 'system', 'claude', 'checklist.seed', 'checklist', 'seed', NULL, ${
  q(JSON.stringify({ items: SEED.length, from: 'launch workplan and the gate plan, 2026-10-19' }))} WHERE NOT EXISTS (SELECT 1 FROM audit_log WHERE action = 'checklist.seed');`);
fs.writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${SEED.length} items, ${SEED.reduce((n, it) => n + (it.parts || []).length, 0)} parts`);
